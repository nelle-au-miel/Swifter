func EvaluationNote(){
    let note = 78
    
    if note >= 90 {
        print("Excellent")
    } else if note >= 80 {
        print("Très bien")
    } else if note >= 70 {
        print("Bien")
    } else if note >= 60 {
        print("Réussite")
    } else {
        print("Échec")
    }
}
